export type StringKey = keyof typeof STRINGS.es;

export const lang = ref<Lang>((localStorage.getItem("cuaderno.lang") as Lang) || "es");

export function setLang(l: Lang): void {
  lang.value = l;
  try {
    localStorage.setItem("cuaderno.lang", l);
  } catch {
    /* private mode */
  }
}

export function t(key: StringKey): string {
  return STRINGS[lang.value][key] ?? STRINGS.es[key] ?? key;
}
